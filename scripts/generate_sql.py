"""Generate sql/create_raw_tables.sql, create_typed_views.sql and validate_data.sql
from semantic/tables.yaml. Deterministic and local: it never calls AWS.

    python scripts/generate_sql.py          # write files
    python scripts/generate_sql.py --check  # exit 1 if files are out of date
"""
import argparse
import sys

from catalog import ROOT, TYPES, load_catalog, resolved_columns, view_columns

SQL_DIR = ROOT / "sql"
HEADER = "-- GENERATED by scripts/generate_sql.py from semantic/tables.yaml. Do not edit by hand.\n"


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def raw_ref(table: dict, col: dict, cols: list[dict]) -> str:
    ref = f'"{col["name"]}"'
    # CRLF files: OpenCSVSerde leaves a trailing carriage return on the last field.
    if table.get("line_ending") == "CRLF" and col["name"] == cols[-1]["name"]:
        ref = f"replace({ref}, chr(13), '')"
    return ref


def clean(ref: str) -> str:
    return f"NULLIF(NULLIF(trim({ref}), ''), 'NULL')"


def typed_expr(col: dict, ref: str, defaults: dict) -> str:
    c = clean(ref)
    t = col["type"]
    if t == "string":
        return c
    if t in ("int", "bigint"):
        return f"try_cast({c} AS {TYPES[t]})"
    if t in ("amount", "rate"):
        return f"try_cast(replace({c}, ',', '') AS {TYPES[t]})"
    if t in ("date", "timestamp"):
        parts = [f"try(date_parse({c}, {q(fmt)}))" for fmt in defaults["date_formats"]]
        expr = f"COALESCE({', '.join(parts)})"
        return f"CAST({expr} AS date)" if t == "date" else expr
    if t == "bool":
        tv = ", ".join(q(v) for v in defaults["true_values"])
        fv = ", ".join(q(v) for v in defaults["false_values"])
        return f"CASE WHEN upper({c}) IN ({tv}) THEN true WHEN upper({c}) IN ({fv}) THEN false END"
    raise ValueError(f"unknown type {t}")


def gen_database(cat: dict) -> str:
    return (
        "-- Creates the Glue Data Catalog database used by Athena. No crawler is used.\n"
        f"CREATE DATABASE IF NOT EXISTS {cat['aws']['database']}\n"
        "COMMENT 'Conversational BI POC V0.1: raw CSV tables and typed views';\n"
    )


def gen_raw(cat: dict) -> str:
    db = cat["aws"]["database"]
    out = [HEADER, "-- Raw staging tables: every column is STRING; typing happens in views.\n"]
    for tname, t in cat["tables"].items():
        cols = resolved_columns(t)
        coldefs = ",\n".join(f"  `{c['name']}` string" for c in cols)
        out.append(
            f"\n-- {t['source_file']} ({len(cols)} columns, {t['line_ending']})\n"
            f"CREATE EXTERNAL TABLE IF NOT EXISTS {db}.raw_{tname} (\n{coldefs}\n)\n"
            "ROW FORMAT SERDE 'org.apache.hadoop.hive.serde2.OpenCSVSerde'\n"
            "WITH SERDEPROPERTIES ('separatorChar' = ',', 'quoteChar' = '\"', 'escapeChar' = '\\\\')\n"
            "STORED AS TEXTFILE\n"
            f"LOCATION '{t['location']}'\n"
            "TBLPROPERTIES ('skip.header.line.count' = '1');\n"
        )
    return "".join(out)


def gen_views(cat: dict) -> str:
    db, defaults = cat["aws"]["database"], cat["defaults"]
    out = [HEADER, "-- Typed views. Columns classified quasi/sensitive/direct PII are excluded.\n"]
    for tname, t in cat["tables"].items():
        cols = resolved_columns(t)
        keep = view_columns(t)
        excluded = len(cols) - len(keep)
        select = ",\n".join(
            f"  {typed_expr(c, raw_ref(t, c, cols), defaults)} AS \"{c['name']}\"" for c in keep
        )
        out.append(
            f"\n-- {len(keep)} of {len(cols)} columns ({excluded} excluded as PII)\n"
            f"CREATE OR REPLACE VIEW {db}.v_{tname} AS\nSELECT\n{select}\nFROM {db}.raw_{tname};\n"
        )
    return "".join(out)


def gen_validation(cat: dict) -> str:
    db, defaults = cat["aws"]["database"], cat["defaults"]
    out = [
        HEADER,
        "-- Data validation. Every query returns AGGREGATES ONLY (counts, min/max, masked shapes,\n"
        "-- flag domains). No row-level or PII values are selected.\n",
    ]
    for tname, t in cat["tables"].items():
        cols = resolved_columns(t)
        keep = view_columns(t)
        raw, view = f"{db}.raw_{tname}", f"{db}.v_{tname}"
        last = raw_ref(t, cols[-1], cols)
        out.append(f"\n-- ===== {tname} =====\n")

        # 1. Row count + structural check (a NULL last column suggests broken/multiline rows).
        out.append(
            f"-- check: {tname}.row_structure\n"
            f"SELECT '{tname}' AS table_name, count(*) AS row_count,\n"
            f"  count_if({clean(last)} IS NULL) AS rows_with_empty_last_column\n"
            f"FROM {raw};\n"
        )

        # 2. Conversion failures: non-empty raw value that did not convert.
        typed = [c for c in keep if c["type"] != "string"]
        if typed:
            fails = ",\n".join(
                f"  count_if({clean(raw_ref(t, c, cols))} IS NOT NULL AND "
                f"{typed_expr(c, raw_ref(t, c, cols), defaults)} IS NULL) AS \"{c['name']}__fail\""
                for c in typed
            )
            out.append(
                f"-- check: {tname}.conversion_failures\n"
                f"SELECT '{tname}' AS table_name, count(*) AS row_count,\n{fails}\nFROM {raw};\n"
            )

        # 3. Date shapes: digits masked to 9, so values are never shown.
        dates = [c for c in keep if c["type"] in ("date", "timestamp")]
        if dates:
            parts = "\nUNION ALL\n".join(
                f"SELECT '{c['name']}' AS column_name, regexp_replace({clean(raw_ref(t, c, cols))}, '[0-9]', '9') AS shape, count(*) AS n FROM {raw} GROUP BY 2"
                for c in dates
            )
            out.append(
                f"-- check: {tname}.date_shapes\n"
                f"SELECT * FROM (\n{parts}\n) ORDER BY column_name, n DESC;\n"
            )

        # 4. Boolean flag domains (raw values of flag columns only).
        bools = [c for c in keep if c["type"] == "bool"]
        if bools:
            parts = "\nUNION ALL\n".join(
                f"SELECT '{c['name']}' AS column_name, upper({clean(raw_ref(t, c, cols))}) AS raw_value, count(*) AS n FROM {raw} GROUP BY 2"
                for c in bools
            )
            out.append(
                f"-- check: {tname}.flag_domains\n"
                f"SELECT * FROM (\n{parts}\n) ORDER BY column_name, n DESC;\n"
            )

        # 5. Typed ranges and cardinality on the view.
        stats = [f"  count(*) AS row_count"]
        for c in keep:
            n = c["name"]
            if c["type"] in ("date", "timestamp"):
                stats += [f'  min("{n}") AS "{n}__min"', f'  max("{n}") AS "{n}__max"']
            elif c["type"] in ("amount", "rate"):
                stats += [f'  count_if("{n}" < 0) AS "{n}__negative"', f'  sum("{n}") AS "{n}__sum"']
            elif c["type"] in ("string", "int", "bigint"):
                stats.append(f'  approx_distinct("{n}") AS "{n}__distinct"')
            stats.append(f'  count_if("{n}" IS NULL) AS "{n}__nulls"')
        out.append(f"-- check: {tname}.typed_profile\nSELECT\n" + ",\n".join(stats) + f"\nFROM {view};\n")

        # 6. Candidate grain uniqueness (unverified grain from tables.yaml).
        grain = t.get("grain_candidate") or []
        if grain:
            g = ", ".join(f'"{x}"' for x in grain)
            out.append(
                f"-- check: {tname}.grain_uniqueness ({', '.join(grain)})\n"
                f"SELECT count(*) AS duplicate_groups, COALESCE(sum(n), 0) AS rows_in_duplicate_groups\n"
                f"FROM (SELECT {g}, count(*) AS n FROM {view} GROUP BY {g} HAVING count(*) > 1);\n"
            )
    return "".join(out)


def outputs(cat: dict) -> dict:
    return {
        SQL_DIR / "create_database.sql": gen_database(cat),
        SQL_DIR / "create_raw_tables.sql": gen_raw(cat),
        SQL_DIR / "create_typed_views.sql": gen_views(cat),
        SQL_DIR / "validate_data.sql": gen_validation(cat),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    stale = []
    for path, text in outputs(load_catalog()).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
